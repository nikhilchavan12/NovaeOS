#!/usr/bin/env python3
"""Generate kernel/gfx/font8x16.c (CP437-indexed) from a Terminus Font PSF1/PSF2 file.

Terminus Font: Copyright (c) 2010 Dimitar Toshkov Zhekov, SIL Open Font License 1.1.
Usage: python3 tools/gen_font.py /usr/share/consolefonts/Uni2-Terminus16.psf.gz > kernel/gfx/font8x16.c
"""
import gzip
import struct
import sys


def load_psf(path):
    data = gzip.open(path).read() if path.endswith(".gz") else open(path, "rb").read()
    if data[:2] == b"\x36\x04":
        mode, height = data[2], data[3]
        assert height == 16, "need an 8x16 PSF font"
        count = 512 if mode & 1 else 256
        glyphs = [data[4 + i * 16: 4 + (i + 1) * 16] for i in range(count)]
        table, pos = {}, 4 + count * 16
        if mode & 2:
            idx, seq = 0, False
            while pos + 1 < len(data) and idx < count:
                (u,) = struct.unpack("<H", data[pos:pos + 2])
                pos += 2
                if u == 0xFFFF:
                    idx, seq = idx + 1, False
                elif u == 0xFFFE:
                    seq = True
                elif not seq:
                    table.setdefault(u, idx)
        return glyphs, table
    magic, _ver, hdr, flags, count, gsize, height, width = struct.unpack("<8I", data[:32])
    assert magic == 0x864AB572 and width == 8 and height == 16, "need an 8x16 PSF2 font"
    glyphs = [data[hdr + i * gsize: hdr + (i + 1) * gsize] for i in range(count)]
    table = {}
    if flags & 1:
        pos, idx = hdr + count * gsize, 0
        buf = data[pos:]
        for entry in buf.split(b"\xff"):
            if idx >= count:
                break
            seq = entry.split(b"\xfe")[0]
            for ch in seq.decode("utf-8", errors="ignore"):
                table.setdefault(ord(ch), idx)
            idx += 1
    return glyphs, table


def main():
    glyphs, table = load_psf(sys.argv[1])
    out = [
        "/* Generated by tools/gen_font.py - do not edit.",
        " * Terminus Font 8x16, Copyright (c) 2010 Dimitar Toshkov Zhekov,",
        " * licensed under the SIL Open Font License 1.1. Indexed by CP437 code. */",
        "",
        "#include <stdint.h>",
        "",
        "const uint8_t font8x16[256][16] = {",
    ]
    low = " \u263a\u263b\u2665\u2666\u2663\u2660\u2022\u25d8\u25cb\u25d9\u2642\u2640\u266a\u266b\u263c" \
          "\u25ba\u25c4\u2195\u203c\u00b6\u00a7\u25ac\u21a8\u2191\u2193\u2192\u2190\u221f\u2194\u25b2\u25bc"
    for code in range(256):
        if code == 0:
            cp = None
        elif code < 32:
            cp = ord(low[code])
        elif code == 0x7F:
            cp = 0x2302
        else:
            cp = ord(bytes([code]).decode("cp437"))
        gi = table.get(cp, table.get(ord("?")) if code >= 32 else None) if cp is not None else None
        rows = glyphs[gi] if gi is not None else bytes(16)
        out.append("    {" + ",".join("0x%02x" % b for b in rows) + "},")
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
